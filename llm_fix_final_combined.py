def parse_datetime(value):
    if isinstance(value, datetime):
        return value
    text = str(value or "").strip()
    if not text:
        return None
    try:
        return datetime.fromisoformat(text.replace("Z", "+00:00"))
    except Exception:
        return None

def unique_nonempty(items):
    """Daftar unik tanpa nilai kosong, mempertahankan urutan kemunculan."""
    seen, result = set(), []
    for it in items:
        val = str(it or "").strip()
        if val and val not in seen:
            seen.add(val)
            result.append(val)
    return result

