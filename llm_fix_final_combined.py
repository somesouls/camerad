def handle_upload(file: UploadFile):
    """Simpan file unggahan, proses, kembalikan (output_path, stats)."""
    filename = file.filename or "fallback_mpnet.xlsx"
    if not filename.lower().endswith(".xlsx"):
        raise HTTPException(status_code=400, detail="File wajib .xlsx")
    if not job_lock.acquire(blocking=False):
        raise HTTPException(status_code=409, detail="Analyzer sedang memproses job lain.")
    try:
        load_qwen()
        print(f"[POST MASUK] filename={filename}, content_type={file.content_type}", flush=True)
        workdir = Path(tempfile.mkdtemp(prefix="qwen_fallback_"))
        input_path = workdir / "input.xlsx"
        output_path = workdir / "hasil_fallback_final.xlsx"
        uploaded_bytes = file.file.read()
        print(f"[UPLOAD SELESAI] {len(uploaded_bytes):,} bytes", flush=True)
        input_path.write_bytes(uploaded_bytes)
        try:
            stats = process_workbook(str(input_path), str(output_path))
        except Exception as exc:
            print(f"[ERROR] {exc}", flush=True)
            raise HTTPException(status_code=400, detail=str(exc)) from exc
        print(f"[SELESAI] hard_gate={stats['hard_gate']}, qwen={stats['qwen']}, "
              f"records={stats['records']}", flush=True)
        return str(output_path), stats
    finally:
        unload_qwen()
        job_lock.release()

