    def clean_base_text(value: object) -> str:
        """Membersihkan HTML, punctuation, whitespace, dan karakter berulang."""
        if value is None or (isinstance(value, float) and pd.isna(value)):
            return ""
        text = html.unescape(str(value)).lower().strip()
        text = re.sub(r"<[^>]+>", " ", text)
        # Standarisasi istilah perpajakan sebelum punctuation dibuang.
        replacements = {
            r"\be[\s\-]*fin\b": "efin",
            r"\bnp[\s\-]*wp\b": "npwp",
            r"\bcore[\s\-]*tax\b": "coretax",
            r"\bdjp[\s\-]*online\b": "djp online",
            r"\bs[\s\-]*p[\s\-]*t\b": "spt",
            r"\bp[\s\-]*p[\s\-]*h\b": "pph",
            r"\bp[\s\-]*p[\s\-]*n\b": "ppn",
            r"\bn[\s\-]*i[\s\-]*k\b": "nik",
        }
        for pattern, replacement in replacements.items():
            text = re.sub(pattern, replacement, text)
        # Huruf berulang 3 kali atau lebih menjadi satu: "tolooong" -> "tolong".
        text = re.sub(r"([a-z])\1{2,}", r"\1", text)
        text = re.sub(r"[^\w\s]", " ", text, flags=re.UNICODE)
        text = re.sub(r"_+", " ", text)
        text = re.sub(r"\s+", " ", text).strip()
        return text


    def normalize_indonesian(value: object) -> str:
        """Normalisasi token slang setelah pembersihan dasar."""
        text = clean_base_text(value)
        if not text:
            return ""
        tokens = text.split()
        normalized_tokens: List[str] = []
        for token in tokens:
            replacement = SLANG_MAP.get(token, token)
            normalized_tokens.extend(replacement.split())
        return " ".join(normalized_tokens).strip()


