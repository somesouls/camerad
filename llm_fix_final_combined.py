def normalize_text(text):
    text = str(text or "").lower().strip()
    return re.sub(r"\s+", " ", text)

def hard_gate(question):
    """Deteksi cepat pertanyaan TIDAK MANDIRI. True -> label 6."""
    q = normalize_text(question)
    if not q:
        return True, "Pertanyaan kosong"
    if not re.search(r"[a-zA-Z\u00c0-\u00ff0-9]", q):
        return True, "Hanya simbol/tanda baca"
    if len(q) == 1:
        return True, "Hanya satu karakter"
    if re.fullmatch(r"\d+", q):
        return True, "Hanya angka/pilihan menu tanpa konteks"
    if q in DEPENDENT_SHORT:
        return True, "Jawaban singkat bergantung konteks sebelumnya"
    for pattern in DEPENDENT_PATTERNS:
        if re.fullmatch(pattern, q):
            return True, "Kalimat lanjutan tanpa konteks mandiri"
    reference = any(x in q for x in CONTEXT_REFERENCES)
    topic = any(x in q for x in TOPIC_TERMS)
    if reference and not topic:
        return True, "Merujuk percakapan sebelumnya tanpa topik eksplisit"
    if len(q.split()) == 1 and len(q) <= 2:
        return True, "Potongan sangat pendek tanpa konteks"
    return False, ""

