    def find_uploaded_file(uploaded_names: Iterable[str], expected_name: str) -> str:
        """Menerima nama asli atau nama hasil duplikasi Colab seperti '(1)'."""
        names = list(uploaded_names)
        if expected_name in names:
            return expected_name
        expected_stem, expected_ext = os.path.splitext(expected_name)
        matches = []
        for name in names:
            stem, ext = os.path.splitext(name)
            if ext.lower() != expected_ext.lower():
                continue
            if stem.lower() == expected_stem.lower() or stem.lower().startswith(
                expected_stem.lower() + " ("
            ):
                matches.append(name)
        if len(matches) == 1:
            return matches[0]
        if not matches:
            raise FileNotFoundError(f"File '{expected_name}' tidak ditemukan.")
        raise ValueError(
            f"Ditemukan beberapa kandidat untuk '{expected_name}': {matches}. "
            "Sisakan satu file saja."
        )


