def _update_usersays_zip(zip_bytes, phrases):
    import io as _io, json as _json, uuid as _uuid, zipfile as _zip, os as _os, re as _re
    zin = _zip.ZipFile(_io.BytesIO(zip_bytes))
    by_key = {}
    for nm in zin.namelist():
        if nm.endswith("/"):
            continue
        base = _os.path.basename(nm)
        if "_usersays" not in base:
            continue
        m = _re.match(r"^(.*)_usersays_([A-Za-z]+)\.json$", base)
        if not m:
            continue
        by_key[(m.group(1), m.group(2).lower())] = nm
    entry_data = {}
    entry_existing = {}
    changed = set()
    report = []
    n_ok = n_dup = n_nf = 0
    for it in phrases:
        intent = str(it.get("id", "")).strip()
        phrase = str(it.get("tp", "")).strip()
        lang = str(it.get("lang", "")).strip().lower()
        if not intent or not phrase:
            continue
        target = by_key.get((intent, lang))
        if not target:
            n_nf += 1
            report.append([intent, lang, phrase,
                           "GAGAL: file usersays_%s untuk intent ini tidak ditemukan" % lang,
                           "-", "Not Found"])
            continue
        if target not in entry_data:
            try:
                dec = _json.loads(zin.read(target).decode("utf-8"))
            except Exception:
                dec = []
            if not isinstance(dec, list):
                dec = []
            entry_data[target] = dec
            ex = set()
            for e in dec:
                if not isinstance(e, dict):
                    continue
                full = "".join(p.get("text", "") for p in e.get("data", []) if isinstance(p, dict))
                ex.add(full.strip().lower())
            entry_existing[target] = ex
        norm = phrase.strip().lower()
        file_only = _os.path.basename(target)
        if norm in entry_existing[target]:
            n_dup += 1
            report.append([intent, lang, phrase,
                           "DIBATALKAN (sudah ada di %s)" % lang, file_only, "Duplikat"])
            continue
        entry_data[target].append({
            "id": str(_uuid.uuid4()),
            "data": [{"text": phrase, "userDefined": False}],
            "isTemplate": False,
            "count": 0,
            "updated": 0,
        })
        entry_existing[target].add(norm)
        changed.add(target)
        n_ok += 1
        report.append([intent, lang, phrase,
                       "BERHASIL ditambahkan ke %s" % lang, file_only, "Sukses"])
    out_buf = _io.BytesIO()
    with _zip.ZipFile(out_buf, "w", _zip.ZIP_DEFLATED) as out:
        for info in zin.infolist():
            nm = info.filename
            if nm.endswith("/"):
                out.writestr(nm, "")
                continue
            if nm in changed:
                out.writestr(nm, _json.dumps(entry_data[nm], ensure_ascii=False, indent=2))
            else:
                out.writestr(nm, zin.read(nm))
    zin.close()
    stats = {"ditambahkan": n_ok, "duplikat": n_dup, "tidak_ketemu": n_nf,
             "file_diperbarui": len(changed), "total": len(report)}
    return out_buf.getvalue(), report, stats


@app.post("/api/update-usersays")
async def update_usersays(
    zip_file: UploadFile = File(...),
    phrases: str = Form(...),
    x_api_key: str | None = Header(default=None),
):
    """Step 11. Suntik training phrase baru ke file usersays_<lang>.json di dalam
    ZIP export Dialogflow. 'phrases' = JSON array [{"id","tp","lang"}]. Balasan
    JSON: {ok, report, stats, zip_b64}. Tidak memakai model/GPU."""
    import json as _json, base64 as _b64
    if x_api_key != API_KEY:
        raise HTTPException(status_code=401, detail="API key tidak valid")
    try:
        items = _json.loads(phrases)
        if not isinstance(items, list):
            raise ValueError("phrases harus berupa array JSON")
    except Exception as e:
        raise HTTPException(status_code=400, detail="phrases JSON tidak valid: %s" % e)
    zip_bytes = await zip_file.read()
    try:
        out_zip, report, stats = _update_usersays_zip(zip_bytes, items)
    except Exception as e:
        raise HTTPException(status_code=400, detail="Gagal memproses ZIP: %s" % e)
    return {
        "ok": True,
        "report": report,
        "stats": stats,
        "zip_b64": _b64.b64encode(out_zip).decode("ascii"),
    }


