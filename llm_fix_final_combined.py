    # ============================================================
    # RERANKER INFERENCE DENGAN OOM RETRY
    # ============================================================
    def score_pairs_with_reranker(
        pairs: Sequence[Tuple[str, str]],
        tokenizer,
        model,
        device: torch.device,
        initial_batch_size: int,
    ) -> np.ndarray:
        """Menghasilkan sigmoid score 0-1 dari raw logit BGE reranker."""
        if not pairs:
            return np.array([], dtype=np.float32)
        batch_size = max(1, initial_batch_size)
        while True:
            all_scores: List[float] = []
            try:
                for start in range(0, len(pairs), batch_size):
                    batch = pairs[start : start + batch_size]
                    queries = [item[0] for item in batch]
                    passages = [item[1] for item in batch]
                    encoded = tokenizer(
                        queries,
                        passages,
                        padding=True,
                        truncation=True,
                        return_tensors="pt",
                        max_length=RERANK_MAX_LENGTH,
                    )
                    encoded = {key: value.to(device) for key, value in encoded.items()}
                    with torch.inference_mode():
                        logits = model(**encoded, return_dict=True).logits
                        logits = logits.view(-1).float()
                        probabilities = torch.sigmoid(logits)
                    all_scores.extend(probabilities.detach().cpu().tolist())
                    del encoded, logits, probabilities
                    if device.type == "cuda":
                        torch.cuda.empty_cache()
                return np.asarray(all_scores, dtype=np.float32)
            except RuntimeError as exc:
                is_oom = "out of memory" in str(exc).lower()
                if not is_oom or batch_size == 1:
                    raise
                batch_size = max(1, batch_size // 2)
                print(
                    f"GPU kehabisan memori. Mengulang reranking dengan batch size {batch_size}."
                )
                all_scores.clear()
                gc.collect()
                if device.type == "cuda":
                    torch.cuda.empty_cache()


    # ============================================================
    # KANDIDAT RETRIEVAL (CONTEXT-AWARE)
    # ============================================================
    def build_candidate_pool(
        query_norm: str,
        query_embedding: np.ndarray,
        semantic_hits: Sequence[dict],
        content_hits: Sequence[dict],
        train_embeddings: np.ndarray,
        train_norm: Sequence[str],
        train_ids: Sequence[str],
        exact_phrase_map: Dict[str, List[int]],
        unique_content_ids: Sequence[str],
        intent_to_phrase_indices: Dict[str, List[int]],
        content_score_map: Dict[str, float],
    ) -> List[dict]:
        """
        Menggabungkan kandidat dari:
          - MPNet (pertanyaan vs training phrase),
          - MPNet (pertanyaan vs ISI INTENT/konteks) -> tarik phrase dari intent itu,
          - RapidFuzz (leksikal, bobot kecil),
          - exact match.
        Lalu menjaga keragaman intent sebelum dikirim ke reranker.
        """
        mpnet_scores: Dict[int, float] = {
            int(hit["corpus_id"]): float(hit["score"]) for hit in semantic_hits
        }

        fuzzy_hits = process.extract(
            query_norm,
            train_norm,
            scorer=fuzz.WRatio,
            processor=None,
            limit=min(RAPIDFUZZ_RETRIEVAL_POOL, len(train_norm)),
        )
        fuzzy_scores: Dict[int, float] = {
            int(idx): float(score) / 100.0 for _, score, idx in fuzzy_hits
        }

        exact_indices = set(exact_phrase_map.get(query_norm, []))

        # Kandidat berbasis KONTEKS: intent yang isi jawabannya dekat dengan
        # pertanyaan, lalu ambil beberapa training phrase terbaik dari intent itu.
        context_indices: set = set()
        for hit in content_hits:
            intent_id = unique_content_ids[int(hit["corpus_id"])]
            phrase_indices = intent_to_phrase_indices.get(intent_id, [])
            if not phrase_indices:
                continue
            ranked = sorted(
                phrase_indices,
                key=lambda i: mpnet_scores.get(
                    i, float(np.dot(query_embedding, train_embeddings[i]))
                ),
                reverse=True,
            )
            for i in ranked[:MAX_PHRASES_PER_INTENT_CANDIDATE]:
                context_indices.add(i)

        candidate_indices = (
            set(mpnet_scores) | set(fuzzy_scores) | exact_indices | context_indices
        )

        candidates: List[dict] = []
        for idx in candidate_indices:
            mpnet_score = mpnet_scores.get(idx)
            if mpnet_score is None:
                mpnet_score = float(np.dot(query_embedding, train_embeddings[idx]))
            rapid_score = fuzzy_scores.get(idx)
            if rapid_score is None:
                rapid_score = fuzz.WRatio(query_norm, train_norm[idx]) / 100.0
            exact_match = idx in exact_indices
            intent_id = train_ids[idx]
            content_score = clip01(content_score_map.get(intent_id, 0.0))

            # Retrieval score: memilih kandidat yang masuk reranker.
            # Konteks (mpnet + isi intent) dominan; leksikal kecil.
            retrieval_score = (
                RETRIEVAL_W_MPNET * clip01(mpnet_score)
                + RETRIEVAL_W_CONTENT * content_score
                + RETRIEVAL_W_RAPIDFUZZ * clip01(rapid_score)
                + (RETRIEVAL_W_EXACT if exact_match else 0.0)
            )
            candidates.append(
                {
                    "idx": idx,
                    "intent_id": intent_id,
                    "mpnet": clip01(mpnet_score),
                    "rapidfuzz": clip01(rapid_score),
                    "content": content_score,
                    "exact": exact_match,
                    "retrieval": retrieval_score,
                }
            )

        candidates.sort(
            key=lambda item: (
                item["retrieval"],
                item["mpnet"],
                item["content"],
                item["exact"],
            ),
            reverse=True,
        )

        # Pass pertama: batasi phrase per intent agar kandidat tidak dikuasai
        # intent dengan training phrase sangat banyak.
        selected: List[dict] = []
        selected_indices = set()
        per_intent = Counter()
        for item in candidates:
            intent_id = item["intent_id"]
            if per_intent[intent_id] >= MAX_PHRASES_PER_INTENT_CANDIDATE:
                continue
            selected.append(item)
            selected_indices.add(item["idx"])
            per_intent[intent_id] += 1
            if len(selected) >= RERANK_TOP_K:
                break

        # Pass kedua: jika belum penuh, isi dari kandidat tersisa.
        if len(selected) < RERANK_TOP_K:
            for item in candidates:
                if item["idx"] in selected_indices:
                    continue
                selected.append(item)
                selected_indices.add(item["idx"])
                if len(selected) >= RERANK_TOP_K:
                    break

        return selected


    # ============================================================
    # AGREGASI PHRASE MENJADI TOP INTENT (CONTEXT-AWARE)
    # ============================================================
    def aggregate_intents(
        candidates: List[dict],
        train_phrases: Sequence[str],
        content_map: Dict[str, str],
        content_score_map: Dict[str, float],
        exact_intent_ids: set,
    ) -> List[dict]:
        """Voting + penggabungan beberapa training phrase menjadi skor per intent."""
        if not candidates:
            return []

        reranked = sorted(
            candidates,
            key=lambda item: (
                item["reranker"],
                item["mpnet"],
                item["content"],
                item["exact"],
            ),
            reverse=True,
        )

        # Reciprocal-log rank voting. Maksimal tiga vote per intent.
        vote_raw: Dict[str, float] = defaultdict(float)
        vote_count = Counter()
        for rank, item in enumerate(reranked[:VOTING_TOP_N], start=1):
            intent_id = item["intent_id"]
            if vote_count[intent_id] >= MAX_VOTES_PER_INTENT:
                continue
            vote_raw[intent_id] += 1.0 / math.log2(rank + 1.0)
            vote_count[intent_id] += 1
        max_vote = max(vote_raw.values(), default=1.0)
        vote_normalized = {
            intent_id: score / max_vote for intent_id, score in vote_raw.items()
        }

        grouped: Dict[str, List[dict]] = defaultdict(list)
        for item in candidates:
            grouped[item["intent_id"]].append(item)

        unique_exact_intent = len(exact_intent_ids) == 1

        intent_results: List[dict] = []
        for intent_id, phrase_items in grouped.items():
            phrase_items.sort(
                key=lambda item: (
                    item["reranker"],
                    item["mpnet"],
                    item["content"],
                    item["exact"],
                ),
                reverse=True,
            )
            top_three = phrase_items[:3]
            best_item = top_three[0]

            best_reranker = max(item["reranker"] for item in top_three)
            mean_reranker = float(np.mean([item["reranker"] for item in top_three]))
            reranker_aggregate = 0.70 * best_reranker + 0.30 * mean_reranker

            mpnet_best = max(item["mpnet"] for item in phrase_items)
            rapid_best = max(item["rapidfuzz"] for item in phrase_items)
            content_value = clip01(content_score_map.get(intent_id, 0.0))
            exact_value = 1.0 if any(item["exact"] for item in phrase_items) else 0.0
            voting_value = vote_normalized.get(intent_id, 0.0)

            # Skor akhir didominasi konteks (reranker + isi intent + semantik phrase).
            final_score = (
                WEIGHT_RERANKER * reranker_aggregate
                + WEIGHT_CONTENT * content_value
                + WEIGHT_MPNET * mpnet_best
                + WEIGHT_VOTING * voting_value
                + WEIGHT_RAPIDFUZZ * rapid_best
                + WEIGHT_EXACT * exact_value
            )
            final_score = clip01(final_score)

            # Exact match = sinyal kuat (lantai skor), BUKAN hard-gate mutlak.
            # Konteks tetap dapat menghasilkan skor lebih tinggi dari lantai ini.
            if exact_value and unique_exact_intent and intent_id in exact_intent_ids:
                final_score = max(final_score, EXACT_UNIQUE_FLOOR)
                method = "EXACT_UNIK"
            else:
                # Ranking TIDAK berubah: floor exact-ambigu tetap diterapkan.
                # Hanya label yang disederhanakan menjadi 2 metode saja.
                if exact_value:
                    final_score = max(final_score, EXACT_AMBIGUOUS_FLOOR)
                method = "HYBRID_RERANK_VOTING"

            representative_idx = best_item["idx"]
            answer = content_map.get(intent_id, "TIDAK DITEMUKAN")
            intent_results.append(
                {
                    "intent_id": intent_id,
                    "final_score": final_score,
                    "trigger_phrase": train_phrases[representative_idx],
                    "answer": answer,
                    "method": method,
                    "mpnet": mpnet_best,
                    "rapidfuzz": rapid_best,
                    "content": content_value,
                    "reranker": reranker_aggregate,
                    "voting": voting_value,
                    "exact": bool(exact_value),
                    "confidence": confidence_label(final_score),
                }
            )

        # Urutkan menurun: Rek 1 = paling tepat/sesuai konteks.
        intent_results.sort(
            key=lambda item: (
                item["final_score"],
                item["reranker"],
                item["content"],
                item["mpnet"],
            ),
            reverse=True,
        )
        return intent_results

