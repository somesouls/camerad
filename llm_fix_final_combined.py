def parse_choice(text):
    """Konversi output LLM menjadi angka 0-6 (0 bila tidak dapat diproses)."""
    value = str(text or "").strip()
    if value in {"0", "1", "2", "3", "4", "5", "6"}:
        return int(value)
    match = re.search(r"(?<!\d)([0-6])(?!\d)", value)
    return int(match.group(1)) if match else 0

def judge_prompts(prompts):
    """Pemilihan intent memakai LLM cloud (OpenAI/Gemini) — output 1 digit 0-6."""
    system_msg = (
        "Anda analis intent chatbot yang ketat. "
        "Jangan menebak konteks yang hilang. "
        "Hormati urutan peringkat: pilih peringkat PERTAMA yang memenuhi (first-fit). "
        "Output tepat satu digit 0 sampai 6."
    )
    choices, raw_outputs = [], []
    total = len(prompts)
    for start in range(0, total, INFERENCE_BATCH_SIZE):
        batch = prompts[start:start + INFERENCE_BATCH_SIZE]
        decoded = llm_client.generate(batch, max_new_tokens=8, system=system_msg)
        raw_outputs.extend(decoded)
        choices.extend(parse_choice(x) for x in decoded)
        print(f"Judgement LLM: {min(start + INFERENCE_BATCH_SIZE, total)}/{total}",
              flush=True)
    return choices, raw_outputs

